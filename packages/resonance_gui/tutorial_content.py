TUTORIAL_CATEGORIES = (
    "快速上手", "工作流程", "货运", "自动战斗", "独立功能", "设置与排障",
)


def _wiki_contents(chapters: tuple[TutorialChapter, ...]) -> str:
    sections = [
        "<p>这里可以按功能查参数，也可以直接搜索界面上的参数名。"
        "每篇说明包含操作步骤、参数作用、与其他选项的关系，以及容易误解的边界。</p>",
        "<h2>先理解三种关系</h2><ul>"
        "<li><b>预算与次数：</b>疲劳预算、整趟用书额度、单段行车用药次数、词缀刷新轮数，"
        "管的是不同资源和范围，不能相互替代。</li>"
        "<li><b>试算与执行：</b>试算使用自己保存的参数；正式运行会重新读取所需游戏状态。"
        "预计收益与实际确认的结果应分别查看。</li>"
        "<li><b>货运与附加客运：</b>附加客运沿货运路线顺带载客，"
        "预计客运收入与货运利润分开记录，不重分配货运疲劳预算。</li></ul>",
        "<h2>参数联动速查</h2>"
        '<table border="1" cellspacing="0" cellpadding="7">'
        "<tr><th>选项或条件</th><th>关联规则</th><th>容易误解的地方</th></tr>"
        "<tr><td>用书策略</td><td>收益优先使用单本收益阈值；优先满仓使用浪费上限</td>"
        "<td>两套条件不会同时生效；都受整趟书额度约束</td></tr>"
        "<tr><td>喝水与便当都开启</td><td>先喝水，重新读取疲劳后再按便当自己的启动线判断</td>"
        "<td>启动阈值不是停止恢复的目标值</td></tr>"
        "<tr><td>固定线路</td><td>使用指定站点顺序，不使用不定线路的收益目标和自由终点</td>"
        "<td>货运内的附加客运也不可用</td></tr>"
        "<tr><td>深潜两种入口</td><td>循环次数控制完整随机循环；策略与安全回合上限作用于关卡内运行</td>"
        "<td>调高一个入口的参数不会改变另一个入口</td></tr>"
        "<tr><td>词缀最多刷新轮数</td><td>先看已有候选，再按提交刷新次数计数</td>"
        "<td>0 只检查候选；轮数不是胶卷消耗总额</td></tr></table>",
    ]
    for category in TUTORIAL_CATEGORIES:
        entries = [chapter for chapter in chapters if chapter.category == category]
        if not entries:
            continue
        sections.append(f"<h2>{escape(category)}</h2><ul>")
        for chapter in entries:
            url = "wiki:" + quote(chapter.title, safe="")
            sections.append(f'<li><a href="{url}">{escape(chapter.title)}</a></li>')
        sections.append("</ul>")
    return "".join(sections)


